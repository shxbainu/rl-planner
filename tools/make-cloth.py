# Writes assets/cloth.png: a seamless 256px greyscale bookcloth weave for the Tab Board's board.
# Mid-grey (128) is neutral under background-blend-mode: soft-light, so the board keeps each class's hue.
# Pure standard library (no PIL). Run: python3 tools/make-cloth.py
import math, random, struct, zlib, pathlib

N, CELL = 256, 4                      # 64 threads each way; tile repeats exactly
rnd = random.Random(1966)
warp = [rnd.uniform(-9, 9) for _ in range(N // CELL)]   # per-thread tone, indexed mod 64 so it tiles
weft = [rnd.uniform(-9, 9) for _ in range(N // CELL)]
slub = [[rnd.uniform(-5, 5) for _ in range(N)] for _ in range(N // CELL)]  # slow along-thread variation

rows = []
for y in range(N):
    row = bytearray([0])  # filter type 0
    ty, fy = divmod(y, CELL)
    for x in range(N):
        tx, fx = divmod(x, CELL)
        over = (tx + ty) % 2 == 0                         # plain weave: warp over on even cells
        f = (fy if over else fx) + 0.5                    # position across the visible thread
        crown = math.sin(math.pi * f / CELL)              # rounded thread: bright crown, dark edges
        tone = (warp[tx] + slub[tx][y % N]) if over else (weft[ty] + slub[ty][x % N])
        v = 128 + 22 * (crown - 0.64) + tone + rnd.uniform(-3, 3)
        row.append(max(0, min(255, int(v))))
    rows.append(bytes(row))

def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", N, N, 8, 0, 0, 0, 0))
png += chunk(b"tEXt", b"Comment\x00Procedural bookcloth weave, generated by tools/make-cloth.py (no source image). Origin: authored for RL Planner Tab Board, Nov 2026.")
png += chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b"")
out = pathlib.Path(__file__).resolve().parent.parent / "assets" / "cloth.png"
out.write_bytes(png)
# self-check: tile edges match in tone on average (seamless) and the mean stays near neutral grey
px = [b for r in rows for b in r[1:]]
mean = sum(px) / len(px)
assert 115 < mean < 141, mean
print(f"wrote {out} ({len(png)} bytes, mean {mean:.1f})")
